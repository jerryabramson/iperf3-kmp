set -e

# Every path below (the bind mount, the build context, third_party/) is relative
# to the repo root, wherever this is invoked from.
cd "$(dirname "$0")/.." >/dev/null   # quiet even when CDPATH is set

# Don't let interactive stuff interfere with us
unset PROMPT_COMMAND PS0 PS2 PS3 PS4 PS5
export PS1="$ "

# Builds an RPM (.rpm) package inside a container, for hosts that can't
# natively produce one - primarily non-Linux hosts like macOS (Debian/Ubuntu
# and Fedora/RHEL can both build their own native package format directly;
# see README.md's packaging table). This is the RPM-side counterpart to
# packageDebianFromContainer.sh.
#
# Verified on:
#   - Fedora x86_64 (Podman) - jpackage's rpmbuild output confirmed to match
#     the glob below (iperf3kmp-1.0.0-1.x86_64.rpm)
#   - macOS (Apple Silicon, Docker Desktop) - native arm64 Linux VM, produced
#     iperf3kmp-1.0.0-1.aarch64.rpm

# --- Container engine detection (Podman or Docker) ---
if command -v podman >/dev/null 2>&1; then
    ENGINE=podman
elif command -v docker >/dev/null 2>&1; then
    ENGINE=docker
else
    echo "ERROR: neither podman nor docker found in PATH." >&2
    exit 1
fi
echo "=== Using container engine: $ENGINE ==="

IMAGE_TAG=compose-rpm-builder
if [ "$ENGINE" = podman ]; then
    IMAGE_REF="localhost/$IMAGE_TAG"
else
    IMAGE_REF="$IMAGE_TAG"
fi

# SELinux volume relabeling (:Z) is only needed/understood on SELinux hosts
# (typically Fedora/RHEL) - never on macOS, and not always on other Linux
# distros either.
VOLUME_SPEC=".:/app"
if command -v getenforce >/dev/null 2>&1 && [ "$(getenforce)" != "Disabled" ]; then
    VOLUME_SPEC=".:/app:Z"
fi

echo "=== Removing this project's stale containers and image ==="
# Deliberately scoped to THIS script's own image ($IMAGE_TAG) and containers
# made from it. An earlier version ran `system prune -a --volumes -f` and
# removed every unused image/volume/container for the user, including
# unrelated projects' (it wiped 17 GB on a shared dev VM).
STALE_CONTAINERS=$($ENGINE ps -a -q --filter "ancestor=$IMAGE_REF" 2>/dev/null || true)
if [ -n "$STALE_CONTAINERS" ]; then
    $ENGINE rm -f $STALE_CONTAINERS
fi
# Untagging the old image also frees its layers (the rebuild below is
# --no-cache), so no dangling images pile up either.
$ENGINE rmi -f "$IMAGE_REF" >/dev/null 2>&1 || true

echo "=== Remapping storage allocation targets ==="
# Podman/buildah stage large temporary image content in TMPDIR. On a machine
# whose root filesystem is small (default /var/tmp), that fills / and the
# build fails; keep it under the home directory instead (override with
# PODMAN_TMP_DIR, which must be on a disk with several GB free). Rootless
# Podman leaves files owned by sub-uids in this directory, which a plain
# `rm -rf` cannot delete ("Permission denied") - `podman unshare` runs the
# removal inside Podman's user namespace where it can.
PODMAN_TMP_DIR="${PODMAN_TMP_DIR:-$HOME/podman_tmp}"
if [ "$ENGINE" = podman ]; then
    podman unshare rm -rf "$PODMAN_TMP_DIR"
else
    rm -rf "$PODMAN_TMP_DIR"
fi
mkdir -p "$PODMAN_TMP_DIR"
export TMPDIR="$PODMAN_TMP_DIR"
FREE_KB=$(df -Pk "$PODMAN_TMP_DIR" | awk 'NR==2 {print $4}')
if [ "${FREE_KB:-0}" -lt 8000000 ]; then
    echo "WARNING: only $((FREE_KB / 1024)) MB free under $PODMAN_TMP_DIR; the build may need ~8 GB." >&2
fi

echo "=== Building fresh image container layer ==="
$ENGINE build --no-cache -t "$IMAGE_TAG" -f scripts/Dockerfile.rpm .

# third_party/iperf's ./configure output (iperf_config.h/version.h,
# gitignored) is arch/OS-specific and cached by compileIperf3Jvm as a
# "already configured" marker. Since the repo dir is bind-mounted into the
# container, a config generated by a prior *native* host build (e.g. a
# macOS ./gradlew run before switching to this container script) leaks in
# and silently miscompiles - e.g. a macOS config defines HAVE_SYS_ENDIAN_H,
# which doesn't exist on Linux, breaking third_party/iperf/src/iperf_api.c
# with "'sys/endian.h' file not found". Clear it so the container always
# regenerates its own.
echo "=== Clearing stale third_party/iperf configure output ==="
rm -f third_party/iperf/src/iperf_config.h third_party/iperf/src/version.h

echo "=== Compiling native package targets ==="
$ENGINE run --rm --pull=never -v "$VOLUME_SPEC" "$IMAGE_REF" ./gradlew :desktopApp:packageRpm

# Guard: the app's own native libraries must not need a newer glibc than the
# oldest supported distro (RHEL 9 family = 2.34). Compilers on newer bases can
# reference e.g. GLIBC_2.38 (__isoc23_strtol) and the package then fails to
# load on older systems.
MAX_GLIBC_ALLOWED=2.34
echo "=== Checking native libraries' glibc requirement (max $MAX_GLIBC_ALLOWED) ==="
MAX_GLIBC_FOUND=$($ENGINE run --rm --pull=never -v "$VOLUME_SPEC" "$IMAGE_REF" sh -c \
    'for f in shared/build/generated/*Resources/*/linux-*/*.so; do objdump -T "$f"; done | grep -o "GLIBC_[0-9.]*" | sed "s/GLIBC_//" | sort -Vu | tail -1')
echo "Highest glibc symbol version needed: ${MAX_GLIBC_FOUND:-none}"
if [ -n "$MAX_GLIBC_FOUND" ] && [ "$(printf '%s\n%s\n' "$MAX_GLIBC_FOUND" "$MAX_GLIBC_ALLOWED" | sort -V | tail -1)" != "$MAX_GLIBC_ALLOWED" ]; then
    echo "ERROR: native libraries need glibc $MAX_GLIBC_FOUND, newer than the supported baseline $MAX_GLIBC_ALLOWED." >&2
    exit 1
fi

OUT_DIR="$(pwd)/desktopApp/build/compose/binaries/main/rpm"

echo "=== Verifying generated package payload ==="
set -x
/bin/ls -ls "$OUT_DIR"
set +x

# RPM's arch suffix (x86_64/aarch64 - uname-style, NOT amd64/arm64 like
# Debian's) depends on the container's arch - glob for it rather than
# guessing.
# Version from the repo-root VERSION file (the cwd is the repo root), not hardcoded.
APP_VERSION="$(tr -d '[:space:]' < VERSION)"
RPM_FILE="$(find "$OUT_DIR" -maxdepth 1 -name "iperf3kmp-${APP_VERSION}-1.*.rpm" -print -quit)"
if [ -z "$RPM_FILE" ]; then
    echo "ERROR: Expected .rpm payload not found in $OUT_DIR!"
    exit 1
fi

echo "SUCCESS: Build process complete! -> $RPM_FILE"
