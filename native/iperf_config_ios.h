/*
 * Hand-written iperf_config.h for iOS (arm64 device + arm64 simulator —
 * both cross-compiled from a macOS host via `xcrun -sdk iphoneos`/
 * `-sdk iphonesimulator`, so there's no on-target ./configure run to
 * generate this the normal way, same situation as Android's
 * iperf_config_android.h).
 *
 * Unlike Android (a different kernel/libc entirely, so that file's values
 * had to be empirically verified against real Android hardware), iOS
 * shares the same Darwin/XNU kernel and BSD socket-option surface as
 * macOS. This is a direct copy of the real ./configure output already
 * produced and verified on this project's macOS desktop build
 * (third_party/iperf/src/iperf_config.h, generated by `./configure
 * --without-sctp --with-openssl=no` — see shared/build.gradle.kts's
 * compileIperf3Jvm task and IPERF3_NATIVE_INTEGRATION.md §6.6) — that
 * output already compiles and links libiperf cleanly on Darwin, and
 * iOS's SDK exposes the same BSD sockopt constants (IP_BOUND_IF,
 * IP_DONTFRAG, SO_BINDTODEVICE-equivalent, etc.) macOS does, so it carries
 * over as-is — verified end-to-end on iOS Simulators and real devices.
 *
 * OpenSSL/SCTP are intentionally unavailable — see
 * IPERF3_NATIVE_INTEGRATION.md §6.6 (this project doesn't use iperf3's auth
 * or SCTP support, and dropping both removes a whole class of per-platform
 * dependency-sourcing problems).
 */

