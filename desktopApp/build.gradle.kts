// Generates AppVersion.kt from the repo-root VERSION file so the CLI
// (cli/CliRunner.kt) can print its own version at runtime -- the GUI build
// tasks above (packageVersion) read VERSION directly since they only need
// it at Gradle-configuration time, but a running CLI process needs it
// compiled in as an actual constant.
val generatedVersionDir = layout.buildDirectory.dir("generated/version/kotlin")
val generateVersionKt = tasks.register("generateVersionKt") {
    group = "build setup"
    description = "Generates cli/AppVersion.kt from the repo-root VERSION file."
    val version = rootProject.extra["appVersion"] as String
    val outputDirProvider = generatedVersionDir
    outputs.dir(outputDirProvider)
    doLast {
        val pkgDir = outputDirProvider.get().asFile
            .resolve("com/jabramson/iperf3_network_tester_kmp/cli")
        pkgDir.mkdirs()
        pkgDir.resolve("AppVersion.kt").writeText(
            """
            |/*
            | * Copyright (c) 2026, Jerold Abramson
            | *
            | * This source code is licensed under the BSD 3-Clause License found in
            | * the LICENSE file in the root directory of this source tree.
            | */
            |
            |// Generated by :desktopApp:generateVersionKt from the repo-root VERSION file -- do not edit by hand.
            |package com.jabramson.iperf3_network_tester_kmp.cli
            |
            |object AppVersion {
            |    const val VERSION = "$version"
            |}
            |""".trimMargin()
        )
    }
}

