// Generates AppVersion.kt from the repo-root VERSION file so the CLI
// (cli/CliRunner.kt) can print its own version at runtime -- the GUI build
// tasks above (packageVersion) read VERSION directly since they only need
// it at Gradle-configuration time, but a running CLI process needs it
// compiled in as an actual constant.
val generatedVersionDir = layout.buildDirectory.dir("generated/version/kotlin")
val generateVersionKt = tasks.register("generateVersionKt") {
    group = "build setup"
    description = "Generates cli/AppVersion.kt from the repo-root VERSION file."
    val version = rootProject.extra["appVersion"] as String
    val outputDirProvider = generatedVersionDir
    outputs.dir(outputDirProvider)
    doLast {
        val pkgDir = outputDirProvider.get().asFile
            .resolve("com/jabramson/iperf3_network_tester_kmp/cli")
        pkgDir.mkdirs()
        pkgDir.resolve("AppVersion.kt").writeText(
            """
            |/*
            | * Copyright (c) 2026, Jerold Abramson
            | *
            | * This source code is licensed under the BSD 3-Clause License found in
            | * the LICENSE file in the root directory of this source tree.
            | */
            |
            |// Generated by :desktopApp:generateVersionKt from the repo-root VERSION file -- do not edit by hand.
            |package com.jabramson.iperf3_network_tester_kmp.cli
            |
            |object AppVersion {
            |    const val VERSION = "$version"
            |}
            |""".trimMargin()
        )
    }
}

kotlin {
    sourceSets {
        main {
            kotlin.srcDir(generateVersionKt)
        }
    }
}

// Windows only: the app drives a real iperf3.exe as a child process (see
// WindowsIperf3ProcessRunner), so the Cygwin-built exe + cygwin1.dll must
// ship inside the app. The Compose plugin bundles everything under
// appResourcesRootDir/<os-arch>/ (here: windows-x64/) into the packaged
// app's resources dir and exposes it at runtime via the
// `compose.application.resources.dir` system property - also set for
// `:desktopApp:run`, so dev runs and the installed .msi resolve the exe
// identically.
// The plugin picks the subfolder by the packaging host's architecture
// (windows-x64 / windows-arm64). On Windows ARM64 the bundled iperf3.exe is
// still the Cygwin x86_64 build (Cygwin has no ARM64 port) and runs under
// Prism emulation, so it is staged under whichever name the plugin expects.
val windowsResourceSubdir = System.getProperty("os.arch").lowercase().let {
    if (it == "aarch64" || it == "arm64") "windows-arm64" else "windows-x64"
}
val stageWindowsIperf3 = tasks.register<Sync>("stageWindowsIperf3") {
    onlyIf { org.gradle.internal.os.OperatingSystem.current().isWindows }
    dependsOn(":shared:compileIperf3ExeWindows")
    from(project(":shared").layout.buildDirectory.dir("generated/iperf3exe/windows-x64"))
    into(layout.buildDirectory.dir("appResources/$windowsResourceSubdir"))
}

// Both opt-in via Gradle properties, not hardcoded -- a contributor/CI building
// this public repo without a real Apple Developer ID cert must still get a
// working (unsigned) packageDmg, not a failure. Set these in your own
// ~/.gradle/gradle.properties (never this repo's own, which is committed):
//   desktopApp.macSigningIdentity=Developer ID Application: Your Name (TEAMID)
//   desktopApp.macNotarizationProfile=<the name you gave `notarytool store-credentials`>
val macSigningIdentity = providers.gradleProperty("desktopApp.macSigningIdentity").orNull
val macNotarizationProfile = providers.gradleProperty("desktopApp.macNotarizationProfile").orNull

compose.desktop {
    application {
        mainClass = "com.jabramson.iperf3_network_tester_kmp.MainKt"

        nativeDistributions {
            appResourcesRootDir.set(layout.buildDirectory.dir("appResources"))
            targetFormats(TargetFormat.Dmg, TargetFormat.Msi, TargetFormat.Deb, TargetFormat.Rpm)
            packageName = "iperf3KMP"
            // Read from the repo-root VERSION file (see root build.gradle.kts),
            // not hardcoded here -- keeps this in sync with Android/iOS/the CLI.
            packageVersion = rootProject.extra["appVersion"] as String

            macOS {
                iconFile.set(project.file("src/main/resources/app-icon.icns"))
                if (macSigningIdentity != null) {
                    // Same bundle ID already used for iOS (Config.xcconfig's
                    // PRODUCT_BUNDLE_IDENTIFIER) -- required once signing is on,
                    // and must use hyphens, not the Android package's underscores
                    // (jpackage/codesign reject underscores in a bundle ID).
                    bundleID = "com.jabramson.iperf3-network-tester-kmp"
                    signing {
                        sign.set(true)
                        identity.set(macSigningIdentity)
                    }
                }
            }
            windows {
                iconFile.set(project.file("src/main/resources/app-icon.ico"))
            }
            linux {
                iconFile.set(project.file("src/main/resources/app-icon.png"))
                // jpackage defaults to "Categories=Unknown" in the generated
                // .desktop file when this is unset, which most desktop
                // environments (GNOME/KDE/XFCE) silently exclude from the
                // application menu, even though the .deb/.rpm postinst's
                // `xdg-desktop-menu install` runs successfully. "Utility" is
                // a valid freedesktop.org main category - shows up under
                // Accessories/Utilities rather than Internet ("Network").
                menuGroup = "Utility"
            }
        }
    }
}

// jpackage's Linux deb backend always emits a postinst/prerm that calls
// `xdg-desktop-menu install`/`uninstall`, with no flag to disable it and no
// supported way to feed jpackage a customized template through the Compose
// Gradle plugin (its `--resource-dir` scratch dir is unconditionally wiped
// by the same task action that invokes jpackage, before any external Gradle
// task-ordering hook could populate it). On a system with no desktop menu
// infrastructure at all (confirmed via a real `apt install ./x.deb` on a
// bare Ubuntu container, e.g. what a default WSL distro looks like) that
// command fails ("xdg-desktop-menu: No writable system menu directory
// found."), and since the generated postinst has `set -e`, that non-zero
// exit aborts the whole `dpkg --configure`, hard-failing the install even
// though the app itself would otherwise work fine. So: patch the already
// -built .deb's maintainer scripts afterward to tolerate that one command
// failing. (The equivalent .rpm scriptlets don't `set -e`, and rpm/dnf only
// warn - not abort - on a non-zero %post exit; confirmed via a real `dnf
// install` on a bare Fedora container with /usr/share/applications removed,
// which succeeded cleanly. No equivalent patch needed there unless someone
// reports an actual rpm install failure.)
val patchDebDesktopMenuScripts = tasks.register("patchDebDesktopMenuScripts") {
    dependsOn("packageDeb")
    outputs.upToDateWhen { false }

    // Resolved here, at configuration time, and captured below as plain
    // Provider<Directory> values - not by referencing `layout` (the
    // project/script receiver) from inside doLast, which is what actually
    // trips the configuration cache's "cannot serialize Gradle script
    // object references" check (the same thing compileIperf3Jvm hits by
    // capturing script-level vals directly, per its own comment in
    // shared/build.gradle.kts). Provider<Directory> resolved ahead of time
    // like this serializes fine.
    val debDirProvider = layout.buildDirectory.dir("compose/binaries/main/deb")
    val extractDirProvider = layout.buildDirectory.dir("compose/tmp/debPatch")

    doLast {
        fun run(vararg cmd: String) {
            val process = ProcessBuilder(*cmd).redirectErrorStream(true).start()
            val output = process.inputStream.bufferedReader().readText()
            val exitCode = process.waitFor()
            check(exitCode == 0) { "Command failed (${cmd.joinToString(" ")}):\n$output" }
        }

        val debDir = debDirProvider.get().asFile
        val debFile = debDir.listFiles { f -> f.extension == "deb" }?.firstOrNull()
            ?: error("No .deb found in $debDir to patch")
        val extractDir = extractDirProvider.get().asFile
        extractDir.deleteRecursively()

        run("dpkg-deb", "-R", debFile.absolutePath, extractDir.absolutePath)

        var patchedAny = false
        for (scriptName in listOf("postinst", "prerm")) {
            val script = extractDir.resolve("DEBIAN/$scriptName")
            if (!script.exists()) continue
            val original = script.readText()
            val patched = original.replace(
                Regex("""^(xdg-desktop-menu (?:install|uninstall) .*?)(?: \|\| true)?$""", RegexOption.MULTILINE)
            ) { "${it.groupValues[1]} || true" }
            if (patched != original) {
                script.writeText(patched)
                patchedAny = true
            }
        }
        check(patchedAny) {
            "Expected to find an `xdg-desktop-menu install/uninstall` line in " +
                "$extractDir/DEBIAN/{postinst,prerm} - jpackage's template may have " +
                "changed, review this task."
        }

        debFile.delete()
        run("fakeroot", "dpkg-deb", "-b", extractDir.absolutePath, debFile.absolutePath)
    }
}
// The Compose plugin registers packageDeb inside its own afterEvaluate, so
// it doesn't exist yet at this point in top-level script evaluation -
// tasks.named() would throw "Task with name 'packageDeb' not found".
afterEvaluate {
    tasks.named("packageDeb") { finalizedBy(patchDebDesktopMenuScripts) }
}

// Notarization and signing are two separate Apple services: jpackage/Compose's
// own `signing` block (wired above) handles signing at package time, but
// *notarizing* needs the already-built .dmg uploaded to Apple afterward, which
// Compose's built-in `notarization` DSL block doesn't reliably support for a
// `notarytool store-credentials` keychain profile (it predates `notarytool` --
// see commit message/PR discussion for why this isn't using that block). So
// notarization is its own explicit post-packageDmg step, shelling out to the
// same `notarytool submit`/`stapler staple` commands documented for manual use.
val notarizeAndStapleDmg = tasks.register("notarizeAndStapleDmg") {
    dependsOn("packageDmg")
    outputs.upToDateWhen { false }

    // Captured into a local val before onlyIf/doLast reference it, not read
    // directly from the outer script-level val inside either lambda -- Kotlin
    // resolves a script-level val from inside a nested lambda via a synthetic
    // reference to the whole enclosing script instance, which is exactly the
    // "cannot serialize Gradle script object references" the configuration
    // cache rejects; a true local variable capture serializes as a plain value.
    val profile = macNotarizationProfile
    val dmgDirProvider = layout.buildDirectory.dir("compose/binaries/main/dmg")

    onlyIf { profile != null }

    doLast {
        fun run(vararg cmd: String): String {
            val process = ProcessBuilder(*cmd).redirectErrorStream(true).start()
            val output = process.inputStream.bufferedReader().readText()
            val exitCode = process.waitFor()
            check(exitCode == 0) { "Command failed (${cmd.joinToString(" ")}):\n$output" }
            return output
        }

        val dmgDir = dmgDirProvider.get().asFile
        val dmgFile = dmgDir.listFiles { f -> f.extension == "dmg" }?.firstOrNull()
            ?: error("No .dmg found in $dmgDir to notarize")

        val submitOutput = run(
            "xcrun", "notarytool", "submit", dmgFile.absolutePath,
            "--keychain-profile", profile!!,
            "--wait"
        )
        println(submitOutput)
        // notarytool submit --wait can exit 0 even when Apple rejects the
        // submission (status: Invalid) -- check the reported status
        // explicitly rather than trusting the exit code alone. On a genuine
        // rejection, `xcrun notarytool log <submission-id> --keychain-profile
        // "$profile"` (id is in submitOutput above) gives the actual reason.
        check(submitOutput.contains("status: Accepted")) {
            "Notarization did not report Accepted -- see output above, " +
                "or run `xcrun notarytool log <submission-id> --keychain-profile \"$profile\"` " +
                "for the full reason."
        }

        run("xcrun", "stapler", "staple", dmgFile.absolutePath)
    }
}
// `packageDmgLocal` below is a fast, local-dev-only alias for packageDmg that
// skips notarizeAndStapleDmg (which can take a while -- a real round trip to
// Apple's notarization service). Whether to wire the finalizer at all has to
// be decided here, at configuration time, before any task runs -- a task
// body can't retroactively un-wire another task's finalizedBy once execution
// has started -- so this checks the requested task names directly rather
// than a project property a task action could toggle too late.
val skipDmgNotarization = gradle.startParameter.taskNames.any {
    it == "packageDmgLocal" || it.endsWith(":packageDmgLocal")
}

// Same afterEvaluate reasoning as packageDeb above -- packageDmg doesn't exist
// yet at top-level script evaluation time either.
afterEvaluate {
    if (!skipDmgNotarization) {
        tasks.named("packageDmg") { finalizedBy(notarizeAndStapleDmg) }
    }
}

tasks.register("packageDmgLocal") {
    group = "compose desktop"
    description = "Like packageDmg, but skips notarizeAndStapleDmg for fast local " +
        "iteration -- the result is signed (if desktopApp.macSigningIdentity is set) " +
        "but not notarized/stapled, so it's fine for testing packaging locally but not " +
        "for distributing to anyone else (Gatekeeper will flag it)."
    dependsOn("packageDmg")
}

